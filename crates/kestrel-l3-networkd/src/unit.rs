//! Rendering of `.network` units from an [`L3Intent`].
//!
//! Every value written comes from a validated model type (interface names,
//! addresses, DNS names), and static configs are re-validated before
//! rendering so no field can inject a newline or another key.

use std::fmt::Write as _;

use kestrel_model::{InterfaceName, Ipv6Mode, ModelError};
use kestrel_ports::l3::{L3Intent, SharedSubnet};

/// Renders the unit Kestrel installs for `link`.
pub fn render(link: &InterfaceName, intent: &L3Intent) -> Result<String, ModelError> {
    if let L3Intent::Static(config) = intent {
        config.validate()?;
    }
    let mut unit = String::new();
    let _ = writeln!(
        unit,
        "# Generated by Kestrel for {link}. Removed automatically; do not edit.\n"
    );
    let _ = writeln!(unit, "[Match]\nName={link}\n");
    match intent {
        L3Intent::DhcpClient {
            ipv6,
            anonymize,
            required_for_online,
        } => {
            if !required_for_online {
                unit.push_str("[Link]\nRequiredForOnline=no\n\n");
            }
            unit.push_str("[Network]\nDHCP=ipv4\n");
            ipv6_lines(&mut unit, *ipv6);
            // Ride out short carrier losses (roaming between APs).
            unit.push_str("IgnoreCarrierLoss=3s\n");
            if *anonymize || !required_for_online {
                unit.push_str("\n[DHCPv4]\n");
                if *anonymize {
                    unit.push_str("Anonymize=yes\n");
                }
                if !required_for_online {
                    // Isolated link (e.g. Wi-Fi Direct client): never let the
                    // remote Group Owner hijack default routes or host DNS.
                    unit.push_str("UseGateway=no\nUseRoutes=no\nUseDNS=no\n");
                }
            }
        }
        L3Intent::Static(config) => {
            unit.push_str("[Network]\n");
            for address in &config.addresses {
                let _ = writeln!(unit, "Address={address}");
            }
            if let Some(gateway) = config.gateway4 {
                let _ = writeln!(unit, "Gateway={gateway}");
            }
            if let Some(gateway) = config.gateway6 {
                let _ = writeln!(unit, "Gateway={gateway}");
            }
            for server in &config.dns {
                let _ = writeln!(unit, "DNS={server}");
            }
            if !config.domains.is_empty() {
                let _ = writeln!(unit, "Domains={}", config.domains.join(" "));
            }
            unit.push_str("IPv6AcceptRA=no\nLinkLocalAddressing=ipv6\nIgnoreCarrierLoss=3s\n");
        }
        L3Intent::SharedSubnet(shared) => render_shared(&mut unit, shared),
    }
    Ok(unit)
}

fn ipv6_lines(unit: &mut String, ipv6: Ipv6Mode) {
    match ipv6 {
        Ipv6Mode::Auto => unit.push_str("IPv6AcceptRA=yes\nLinkLocalAddressing=ipv6\n"),
        Ipv6Mode::Disabled => unit.push_str("IPv6AcceptRA=no\nLinkLocalAddressing=no\n"),
    }
}

fn render_shared(unit: &mut String, shared: &SharedSubnet) {
    unit.push_str("[Link]\nRequiredForOnline=no\n\n");
    let _ = writeln!(unit, "[Network]\nAddress={}", shared.address);
    unit.push_str(
        "ConfigureWithoutCarrier=yes\nIgnoreCarrierLoss=yes\n\
         DHCPServer=yes\nIPv6AcceptRA=no\nLinkLocalAddressing=no\n",
    );
    if shared.masquerade {
        unit.push_str("IPMasquerade=ipv4\n");
    }
    let _ = writeln!(
        unit,
        "\n[DHCPServer]\nPoolOffset={}\nPoolSize={}",
        shared.pool_offset, shared.pool_size
    );
    // Without an uplink there is no DNS to offer; with one, networkd's
    // default (the uplink's servers) applies.
    if !shared.emit_router {
        unit.push_str("EmitRouter=no\nEmitDNS=no\n");
    }
    // Leases are as ephemeral as the link. Without this, networkd 256+
    // waits for persistent storage before starting the server.
    unit.push_str("PersistLeases=runtime\n");
}

#[cfg(test)]
mod tests {
    use kestrel_model::StaticIp;

    use super::*;

    fn link(name: &str) -> InterfaceName {
        InterfaceName::new(name).unwrap()
    }

    #[test]
    fn station_dhcp_unit() {
        let unit = render(
            &link("wlan0"),
            &L3Intent::DhcpClient {
                ipv6: Ipv6Mode::Auto,
                anonymize: false,
                required_for_online: true,
            },
        )
        .unwrap();
        assert_eq!(
            unit,
            "# Generated by Kestrel for wlan0. Removed automatically; do not edit.\n\n\
             [Match]\nName=wlan0\n\n\
             [Network]\nDHCP=ipv4\nIPv6AcceptRA=yes\nLinkLocalAddressing=ipv6\nIgnoreCarrierLoss=3s\n"
        );
    }

    #[test]
    fn p2p_client_unit_is_anonymous_and_isolated() {
        let unit = render(
            &link("p2p-wlan0-0"),
            &L3Intent::DhcpClient {
                ipv6: Ipv6Mode::Disabled,
                anonymize: true,
                required_for_online: false,
            },
        )
        .unwrap();
        assert!(unit.contains("[Link]\nRequiredForOnline=no\n"));
        assert!(unit.contains("IPv6AcceptRA=no\nLinkLocalAddressing=no\n"));
        assert!(
            unit.ends_with("[DHCPv4]\nAnonymize=yes\nUseGateway=no\nUseRoutes=no\nUseDNS=no\n")
        );
    }

    #[test]
    fn group_owner_unit() {
        let unit = render(
            &link("p2p-wlan0-0"),
            &L3Intent::SharedSubnet(SharedSubnet {
                address: "192.168.49.1/24".parse().unwrap(),
                pool_offset: 2,
                pool_size: 253,
                emit_router: false,
                masquerade: false,
            }),
        )
        .unwrap();
        assert_eq!(
            unit,
            "# Generated by Kestrel for p2p-wlan0-0. Removed automatically; do not edit.\n\n\
             [Match]\nName=p2p-wlan0-0\n\n\
             [Link]\nRequiredForOnline=no\n\n\
             [Network]\nAddress=192.168.49.1/24\nConfigureWithoutCarrier=yes\nIgnoreCarrierLoss=yes\nDHCPServer=yes\nIPv6AcceptRA=no\nLinkLocalAddressing=no\n\n\
             [DHCPServer]\nPoolOffset=2\nPoolSize=253\nEmitRouter=no\nEmitDNS=no\nPersistLeases=runtime\n"
        );
    }

    #[test]
    fn hotspot_style_unit_masquerades() {
        let unit = render(
            &link("ap0"),
            &L3Intent::SharedSubnet(SharedSubnet {
                address: "10.49.0.1/24".parse().unwrap(),
                pool_offset: 2,
                pool_size: 253,
                emit_router: true,
                masquerade: true,
            }),
        )
        .unwrap();
        assert!(unit.contains("IPMasquerade=ipv4\n"));
        assert!(unit.contains("ConfigureWithoutCarrier=yes\n"));
        assert!(!unit.contains("EmitRouter=no"));
    }

    #[test]
    fn static_unit_and_injection_rejection() {
        let unit = render(
            &link("wlan0"),
            &L3Intent::Static(StaticIp {
                addresses: vec![
                    "192.0.2.10/24".parse().unwrap(),
                    "2001:db8::10/64".parse().unwrap(),
                ],
                gateway4: Some("192.0.2.1".parse().unwrap()),
                gateway6: Some("fe80::1".parse().unwrap()),
                dns: vec!["192.0.2.53".parse().unwrap()],
                domains: vec!["example.org".into(), "~corp".into()],
            }),
        )
        .unwrap();
        assert!(unit.contains(
            "Address=192.0.2.10/24\nAddress=2001:db8::10/64\nGateway=192.0.2.1\nGateway=fe80::1\n\
             DNS=192.0.2.53\nDomains=example.org ~corp\n"
        ));

        let injected = StaticIp {
            addresses: vec!["192.0.2.10/24".parse().unwrap()],
            domains: vec!["example.org\n[Route]\nGateway=1.2.3.4".into()],
            ..StaticIp::default()
        };
        assert!(render(&link("wlan0"), &L3Intent::Static(injected)).is_err());
    }
}
