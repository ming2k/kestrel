//! One Wi-Fi Direct connection: GO negotiation, group formation, role-driven
//! L3, and teardown.
//!
//! ```text
//! Negotiating ─GO-neg ok→ Forming ─GroupStarted{role, if}→ ConfiguringL3 ─ready→ Ready
//!      │                     │                                  │                  │
//!      └── fail/timeout ─────┴──────────────────────────────────┴──── close/end ───┘
//!                                         ▼
//!                       Closed (all held resources released in reverse)
//! ```
//!
//! The negotiated role decides L3:
//! - **Group Owner**: a shared subnet with a DHCP server on the group interface.
//! - **Client**: a DHCP client on the group interface.

use std::net::IpAddr;
use std::time::{Duration, Instant};

use kestrel_model::{
    FailureReason, GoIntent, InterfaceName, MacAddress, P2pGroupId, P2pRole, WpsMethod, WpsPin,
};

use crate::timer::{TimerToken, Timers};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionConfig {
    /// Covers provision discovery and the user typing or pressing on the
    /// peer, so it is generous.
    pub negotiation_timeout: Duration,
    pub formation_timeout: Duration,
    pub l3_timeout: Duration,
}

impl Default for SessionConfig {
    fn default() -> Self {
        Self {
            negotiation_timeout: Duration::from_secs(120),
            formation_timeout: Duration::from_secs(30),
            l3_timeout: Duration::from_secs(30),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SessionState {
    Negotiating {
        /// PIN generated by the backend for [`WpsMethod::DisplayPin`].
        pin: Option<WpsPin>,
    },
    Forming {
        role: P2pRole,
    },
    ConfiguringL3 {
        role: P2pRole,
        group_if: InterfaceName,
    },
    Ready {
        role: P2pRole,
        group_if: InterfaceName,
        /// The peer's IP address once known: the DHCP lease we handed out
        /// as GO, or the GO's address as client.
        peer_ip: Option<IpAddr>,
    },
    Closed {
        /// `None` for a clean close requested by a consumer.
        reason: Option<FailureReason>,
    },
}

impl SessionState {
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::Negotiating { .. } => "negotiating",
            Self::Forming { .. } => "forming",
            Self::ConfiguringL3 { .. } => "configuring-l3",
            Self::Ready { .. } => "ready",
            Self::Closed { .. } => "closed",
        }
    }

    pub const fn role(&self) -> Option<P2pRole> {
        match self {
            Self::Forming { role }
            | Self::ConfiguringL3 { role, .. }
            | Self::Ready { role, .. } => Some(*role),
            Self::Negotiating { .. } | Self::Closed { .. } => None,
        }
    }

    pub const fn group_interface(&self) -> Option<&InterfaceName> {
        match self {
            Self::ConfiguringL3 { group_if, .. } | Self::Ready { group_if, .. } => Some(group_if),
            _ => None,
        }
    }
}

/// What L3 should do on the group interface.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum L3Request {
    /// Allocate a subnet, take its first host address, serve DHCP.
    SharedSubnet,
    /// Obtain an address from the remote GO.
    DhcpClient,
}

impl L3Request {
    pub const fn for_role(role: P2pRole) -> Self {
        match role {
            P2pRole::GroupOwner => Self::SharedSubnet,
            P2pRole::Client => Self::DhcpClient,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum SessionTimer {
    Negotiation,
    Formation,
    L3,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SessionCommandKind {
    Connect,
    StartGroup,
    ConnectPersistent,
    StartPersistentGroup,
    AuthorizeGroup,
    CancelNegotiation,
    BindL3,
    UnbindL3,
    RemoveGroup,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SessionInput {
    Close,
    ConnectAccepted {
        generated_pin: Option<WpsPin>,
    },
    GoNegotiationSucceeded {
        role: P2pRole,
    },
    GoNegotiationFailed {
        status: u8,
    },
    WpsFailed,
    GroupStarted {
        group_if: InterfaceName,
        role: P2pRole,
    },
    GroupFinished {
        group_if: InterfaceName,
    },
    L3Ready {
        peer_ip: Option<IpAddr>,
    },
    L3Failed(String),
    CommandFailed {
        command: SessionCommandKind,
        reason: FailureReason,
    },
    DeviceUnavailable,
    Timer {
        kind: SessionTimer,
        token: TimerToken,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SessionCommand {
    Connect {
        peer: MacAddress,
        method: WpsMethod,
        go_intent: GoIntent,
        persistent: bool,
    },
    /// Start a group as owner without GO negotiation.
    StartGroup {
        frequency: Option<u32>,
        persistent: bool,
    },
    /// Reinvoke a saved persistent group with `peer`.
    ConnectPersistent {
        group_id: P2pGroupId,
        peer: MacAddress,
        frequency: Option<u32>,
    },
    /// Start a saved persistent group as Group Owner without WPS.
    StartPersistentGroup {
        group_id: P2pGroupId,
        frequency: Option<u32>,
    },
    /// Arm WPS push-button on an autonomous group.
    AuthorizeGroup {
        group_if: InterfaceName,
    },
    CancelNegotiation,
    BindL3 {
        link: InterfaceName,
        request: L3Request,
    },
    UnbindL3 {
        link: InterfaceName,
    },
    RemoveGroup {
        group_if: InterfaceName,
    },
    StartTimer {
        kind: SessionTimer,
        token: TimerToken,
        after: Duration,
    },
}

/// An external resource the session holds.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SessionHeld {
    Negotiation,
    Group(InterfaceName),
    L3Binding(InterfaceName),
}

#[derive(Debug)]
pub struct P2pSession {
    config: SessionConfig,
    /// `None` for an autonomous group (no peer was negotiated with).
    peer: Option<MacAddress>,
    /// `None` for an autonomous group (no WPS provisioning).
    method: Option<WpsMethod>,
    go_intent: GoIntent,
    persistent: bool,
    reused_group: Option<P2pGroupId>,
    state: SessionState,
    held: Vec<SessionHeld>,
    timers: Timers<SessionTimer>,
    out: Vec<SessionCommand>,
}

impl P2pSession {
    /// Creates the session and returns the commands that start it.
    pub fn start(
        config: SessionConfig,
        peer: MacAddress,
        method: WpsMethod,
        go_intent: GoIntent,
    ) -> (Self, Vec<SessionCommand>) {
        Self::start_with_options(config, peer, method, go_intent, false)
    }

    pub fn start_with_options(
        config: SessionConfig,
        peer: MacAddress,
        method: WpsMethod,
        go_intent: GoIntent,
        persistent: bool,
    ) -> (Self, Vec<SessionCommand>) {
        let mut session = Self {
            config,
            peer: Some(peer),
            method: Some(method.clone()),
            go_intent,
            persistent,
            reused_group: None,
            state: SessionState::Negotiating { pin: None },
            held: vec![SessionHeld::Negotiation],
            timers: Timers::new(),
            out: Vec::new(),
        };
        session.out.push(SessionCommand::Connect {
            peer,
            method,
            go_intent,
            persistent,
        });
        session.arm(
            SessionTimer::Negotiation,
            session.config.negotiation_timeout,
        );
        let commands = std::mem::take(&mut session.out);
        (session, commands)
    }

    /// Creates a session that starts a group as owner without GO
    /// negotiation (autonomous GO). The group SSID is chosen by the backend.
    pub fn start_autonomous(
        config: SessionConfig,
        frequency: Option<u32>,
    ) -> (Self, Vec<SessionCommand>) {
        Self::start_autonomous_with_options(config, frequency, false)
    }

    pub fn start_autonomous_with_options(
        config: SessionConfig,
        frequency: Option<u32>,
        persistent: bool,
    ) -> (Self, Vec<SessionCommand>) {
        let mut session = Self {
            config,
            peer: None,
            method: None,
            go_intent: GoIntent::MAX,
            persistent,
            reused_group: None,
            state: SessionState::Forming {
                role: P2pRole::GroupOwner,
            },
            // The group-add operation is the resource to cancel if the
            // session closes before the group exists.
            held: vec![SessionHeld::Negotiation],
            timers: Timers::new(),
            out: Vec::new(),
        };
        session.out.push(SessionCommand::StartGroup {
            frequency,
            persistent,
        });
        session.arm(SessionTimer::Formation, session.config.formation_timeout);
        let commands = std::mem::take(&mut session.out);
        (session, commands)
    }

    /// Reinvokes a saved persistent P2P group with `peer` without WPS.
    pub fn connect_persistent(
        config: SessionConfig,
        group_id: P2pGroupId,
        peer: MacAddress,
        frequency: Option<u32>,
    ) -> (Self, Vec<SessionCommand>) {
        let mut session = Self {
            config,
            peer: Some(peer),
            method: None,
            go_intent: GoIntent::default(),
            persistent: true,
            reused_group: Some(group_id),
            state: SessionState::Negotiating { pin: None },
            held: vec![SessionHeld::Negotiation],
            timers: Timers::new(),
            out: Vec::new(),
        };
        session.out.push(SessionCommand::ConnectPersistent {
            group_id,
            peer,
            frequency,
        });
        session.arm(
            SessionTimer::Negotiation,
            session.config.negotiation_timeout,
        );
        let commands = std::mem::take(&mut session.out);
        (session, commands)
    }

    /// Starts a saved persistent P2P group as Group Owner without WPS.
    pub fn start_persistent_group(
        config: SessionConfig,
        group_id: P2pGroupId,
        frequency: Option<u32>,
    ) -> (Self, Vec<SessionCommand>) {
        let mut session = Self {
            config,
            peer: None,
            method: None,
            go_intent: GoIntent::MAX,
            persistent: true,
            reused_group: Some(group_id),
            state: SessionState::Forming {
                role: P2pRole::GroupOwner,
            },
            held: vec![SessionHeld::Negotiation],
            timers: Timers::new(),
            out: Vec::new(),
        };
        session.out.push(SessionCommand::StartPersistentGroup {
            group_id,
            frequency,
        });
        session.arm(SessionTimer::Formation, session.config.formation_timeout);
        let commands = std::mem::take(&mut session.out);
        (session, commands)
    }

    pub const fn is_persistent(&self) -> bool {
        self.persistent
    }

    pub const fn peer(&self) -> Option<MacAddress> {
        self.peer
    }

    pub fn method(&self) -> Option<&WpsMethod> {
        self.method.as_ref()
    }

    pub const fn go_intent(&self) -> GoIntent {
        self.go_intent
    }

    /// True when this session owns a group it started itself, without a
    /// negotiated peer.
    pub const fn is_autonomous(&self) -> bool {
        self.peer.is_none()
    }

    pub const fn state(&self) -> &SessionState {
        &self.state
    }

    pub fn held(&self) -> &[SessionHeld] {
        &self.held
    }

    pub const fn is_closed(&self) -> bool {
        matches!(self.state, SessionState::Closed { .. })
    }

    pub fn handle(&mut self, now: Instant, input: SessionInput) -> Vec<SessionCommand> {
        let _ = now;
        if self.is_closed() {
            return Vec::new();
        }
        match input {
            SessionInput::Close => self.end(None),
            SessionInput::ConnectAccepted { generated_pin } => {
                if let SessionState::Negotiating { pin } = &mut self.state {
                    *pin = generated_pin;
                }
            }
            SessionInput::GoNegotiationSucceeded { role } => {
                if matches!(self.state, SessionState::Negotiating { .. }) {
                    self.timers.cancel(SessionTimer::Negotiation);
                    self.state = SessionState::Forming { role };
                    self.arm(SessionTimer::Formation, self.config.formation_timeout);
                }
            }
            SessionInput::GoNegotiationFailed { status } => {
                if self.before_group() {
                    self.end(Some(FailureReason::NegotiationFailed(status)));
                }
            }
            SessionInput::WpsFailed => {
                if self.before_group() {
                    self.end(Some(FailureReason::WpsFailed));
                }
            }
            SessionInput::GroupStarted { group_if, role } => self.group_started(group_if, role),
            SessionInput::GroupFinished { group_if } => self.group_finished(&group_if),
            SessionInput::L3Ready { peer_ip } => match &mut self.state {
                SessionState::ConfiguringL3 { role, group_if } => {
                    self.timers.cancel(SessionTimer::L3);
                    self.state = SessionState::Ready {
                        role: *role,
                        group_if: group_if.clone(),
                        peer_ip,
                    };
                }
                SessionState::Ready { peer_ip: known, .. } if peer_ip.is_some() => {
                    *known = peer_ip;
                }
                _ => {}
            },
            SessionInput::L3Failed(detail) => {
                if matches!(
                    self.state,
                    SessionState::ConfiguringL3 { .. } | SessionState::Ready { .. }
                ) {
                    self.end(Some(FailureReason::L3Failed(detail)));
                }
            }
            SessionInput::CommandFailed { command, reason } => match command {
                SessionCommandKind::Connect
                | SessionCommandKind::StartGroup
                | SessionCommandKind::ConnectPersistent
                | SessionCommandKind::StartPersistentGroup => {
                    if self.before_group() {
                        self.end(Some(reason));
                    }
                }
                SessionCommandKind::AuthorizeGroup => {
                    if matches!(
                        self.state,
                        SessionState::ConfiguringL3 { .. } | SessionState::Ready { .. }
                    ) {
                        self.end(Some(reason));
                    }
                }
                SessionCommandKind::BindL3 => {
                    if matches!(self.state, SessionState::ConfiguringL3 { .. }) {
                        let reason = match reason {
                            FailureReason::NoSubnet => FailureReason::NoSubnet,
                            other => FailureReason::L3Failed(other.to_string()),
                        };
                        self.end(Some(reason));
                    }
                }
                // Best-effort cleanup; the startup sweep covers leftovers.
                SessionCommandKind::CancelNegotiation
                | SessionCommandKind::UnbindL3
                | SessionCommandKind::RemoveGroup => {}
            },
            SessionInput::DeviceUnavailable => {
                self.end(Some(FailureReason::DeviceUnavailable));
            }
            SessionInput::Timer { kind, token } => {
                if self.timers.fire(kind, token) {
                    let stage = match kind {
                        SessionTimer::Negotiation => "GO negotiation",
                        SessionTimer::Formation => "group formation",
                        SessionTimer::L3 => "L3 configuration",
                    };
                    self.end(Some(FailureReason::Timeout(stage.to_owned())));
                }
            }
        }
        std::mem::take(&mut self.out)
    }

    const fn before_group(&self) -> bool {
        matches!(
            self.state,
            SessionState::Negotiating { .. } | SessionState::Forming { .. }
        )
    }

    fn group_finished(&mut self, group_if: &InterfaceName) {
        let position = self
            .held
            .iter()
            .position(|held| *held == SessionHeld::Group(group_if.clone()));
        if let Some(position) = position {
            // The group is already gone; nothing to remove.
            self.held.remove(position);
            self.end(Some(FailureReason::PeerDisconnected));
        } else if self.is_autonomous() && matches!(self.state, SessionState::Forming { .. }) {
            // The group we asked to start ended before its GroupStarted
            // event reached us.
            self.end(Some(FailureReason::PeerDisconnected));
        }
    }

    fn group_started(&mut self, group_if: InterfaceName, role: P2pRole) {
        if !self.before_group() {
            // A second group on the same device is not ours.
            return;
        }
        self.timers.cancel(SessionTimer::Negotiation);
        self.timers.cancel(SessionTimer::Formation);
        // Negotiation is complete; the group now represents the session.
        self.held.retain(|held| *held != SessionHeld::Negotiation);
        self.held.push(SessionHeld::Group(group_if.clone()));
        self.held.push(SessionHeld::L3Binding(group_if.clone()));
        if self.is_autonomous() && self.reused_group.is_none() {
            // A fresh autonomous GO formed without negotiation has not run WPS.
            // Arm push-button so one client can provision into the group.
            self.out.push(SessionCommand::AuthorizeGroup {
                group_if: group_if.clone(),
            });
        }
        self.out.push(SessionCommand::BindL3 {
            link: group_if.clone(),
            request: L3Request::for_role(role),
        });
        self.arm(SessionTimer::L3, self.config.l3_timeout);
        self.state = SessionState::ConfiguringL3 { role, group_if };
    }

    /// Releases every held resource in reverse order and closes.
    fn end(&mut self, reason: Option<FailureReason>) {
        while let Some(held) = self.held.pop() {
            self.out.push(match held {
                SessionHeld::Negotiation => SessionCommand::CancelNegotiation,
                SessionHeld::Group(group_if) => SessionCommand::RemoveGroup { group_if },
                SessionHeld::L3Binding(link) => SessionCommand::UnbindL3 { link },
            });
        }
        self.timers.clear();
        self.state = SessionState::Closed { reason };
    }

    fn arm(&mut self, kind: SessionTimer, after: Duration) {
        let token = self.timers.arm(kind);
        self.out
            .push(SessionCommand::StartTimer { kind, token, after });
    }
}

