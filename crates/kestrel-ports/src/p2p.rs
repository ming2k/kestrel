//! Wi-Fi Direct (P2P) port.

use std::fmt;
use std::time::Duration;

use async_trait::async_trait;
use kestrel_model::{
    GoIntent, InterfaceName, MacAddress, P2pPeer, P2pRole, Secret, Ssid, WpsMethod, WpsPin,
};

use crate::{PortError, PortResult, Subscription};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct P2pConnectRequest {
    pub peer: MacAddress,
    pub method: WpsMethod,
    pub go_intent: GoIntent,
    pub persistent: bool,
}

/// Parameters for starting a group as owner without GO negotiation
/// (autonomous GO). The group SSID is generated by the backend.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct P2pGroupRequest {
    /// Operating channel in MHz. `None` lets the backend choose.
    pub frequency: Option<u32>,
    pub persistent: bool,
}

/// Parameters to reinvoke a saved persistent P2P group with a peer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PersistentGroupConnect {
    pub peer: MacAddress,
    pub role: P2pRole,
    pub ssid: Ssid,
    pub go_address: MacAddress,
    pub psk: Secret,
    pub frequency: Option<u32>,
}

/// Device-level P2P settings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct P2pDeviceConfig {
    pub device_name: String,
    /// Wi-Fi Display subelements to advertise (Miracast). `None` disables
    /// WFD.
    pub wfd_subelements: Option<Vec<u8>>,
}

/// How a remote peer asked to be provisioned.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RequestedMethod {
    PushButton,
    Pin,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum P2pEvent {
    PeerFound {
        device: InterfaceName,
        peer: P2pPeer,
    },
    PeerLost {
        device: InterfaceName,
        address: MacAddress,
    },
    FindStopped {
        device: InterfaceName,
    },
    /// A remote peer started GO negotiation with us.
    NegotiationRequest {
        device: InterfaceName,
        peer: MacAddress,
        method: RequestedMethod,
    },
    /// A remote peer invited us to reinvoke a group.
    InvitationReceived {
        device: InterfaceName,
        peer: MacAddress,
        go_address: MacAddress,
        persistent: bool,
    },
    GoNegotiationSucceeded {
        device: InterfaceName,
        role: P2pRole,
    },
    GoNegotiationFailed {
        device: InterfaceName,
        status: u8,
    },
    GroupStarted {
        device: InterfaceName,
        group_if: InterfaceName,
        role: P2pRole,
    },
    /// Emitted when a persistent group's credentials were provisioned so
    /// Kestrel can persist them in its own encrypted store.
    PersistentGroupFormed {
        device: InterfaceName,
        role: P2pRole,
        ssid: Ssid,
        go_address: MacAddress,
        psk: Secret,
    },
    GroupFinished {
        device: InterfaceName,
        group_if: InterfaceName,
    },
    WpsFailed {
        device: InterfaceName,
    },
}

#[async_trait]
pub trait P2pProvider: Send + Sync + fmt::Debug {
    fn subscribe(&self) -> Subscription<P2pEvent>;

    async fn configure(&self, device: &InterfaceName, config: &P2pDeviceConfig) -> PortResult<()>;

    async fn find(&self, device: &InterfaceName, timeout: Duration) -> PortResult<()>;

    async fn stop_find(&self, device: &InterfaceName) -> PortResult<()>;

    async fn peers(&self, device: &InterfaceName) -> PortResult<Vec<P2pPeer>>;

    /// Starts GO negotiation (or answers a peer's request). Returns the PIN
    /// the backend generated for [`WpsMethod::DisplayPin`].
    async fn connect(
        &self,
        device: &InterfaceName,
        request: &P2pConnectRequest,
    ) -> PortResult<Option<WpsPin>>;

    /// Starts a group as owner without GO negotiation (autonomous GO).
    /// [`P2pEvent::GroupStarted`] reports the group interface and role.
    async fn start_group(
        &self,
        device: &InterfaceName,
        request: &P2pGroupRequest,
    ) -> PortResult<()>;

    /// Reinvokes a saved persistent group with `request.peer`.
    async fn connect_persistent(
        &self,
        _device: &InterfaceName,
        _request: &PersistentGroupConnect,
    ) -> PortResult<()> {
        Err(PortError::NotSupported(
            "persistent P2P groups are not supported by this backend".to_owned(),
        ))
    }

    /// Starts a saved persistent group as autonomous Group Owner without WPS.
    async fn start_persistent_group(
        &self,
        _device: &InterfaceName,
        _ssid: &Ssid,
        _go_address: MacAddress,
        _psk: &Secret,
        _frequency: Option<u32>,
    ) -> PortResult<()> {
        Err(PortError::NotSupported(
            "persistent P2P groups are not supported by this backend".to_owned(),
        ))
    }

    /// Allows one WPS push-button enrollee to join a group we own. Used
    /// after an autonomous group starts, so a phone can provision into it.
    async fn authorize_group(
        &self,
        device: &InterfaceName,
        group_if: &InterfaceName,
    ) -> PortResult<()>;

    /// Aborts an ongoing negotiation. Idempotent.
    async fn cancel(&self, device: &InterfaceName) -> PortResult<()>;

    /// Removes a group this device is part of. Idempotent.
    async fn remove_group(
        &self,
        device: &InterfaceName,
        group_if: &InterfaceName,
    ) -> PortResult<()>;
}
